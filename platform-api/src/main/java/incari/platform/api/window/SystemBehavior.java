package incari.platform.api.window;

/** Desktop behaviors the game lets the player toggle in its options. */
public enum SystemBehavior {
    /** macOS: a Control-click acts as a right click, as on a one-button mouse. */
    CTRL_CLICK_IS_RIGHT_CLICK,
    /** macOS: the menu bar slides down in fullscreen when the pointer reaches the top. */
    MENU_BAR_IN_FULLSCREEN
}
