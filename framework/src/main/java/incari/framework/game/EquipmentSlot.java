package incari.framework.game;

/** Where the player wears or holds an item. */
public enum EquipmentSlot {
    /** The helmet. */
    HEAD,
    /** The chestplate (or elytra). */
    CHEST,
    /** The leggings. */
    LEGS,
    /** The boots. */
    FEET,
    /** The item in the main hand. */
    MAINHAND,
    /** The item in the off hand. */
    OFFHAND
}
