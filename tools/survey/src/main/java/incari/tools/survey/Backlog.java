package incari.tools.survey;

import incari.tools.build.Log;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.function.Function;
import java.util.stream.Collectors;

/**
 * Renders {@code docs/port-backlog.md} from the triaged findings.
 *
 * <p>The file is tracked, so it holds only API names, package names and counts: never game
 * code, and never Mojang member names (callers are summarized by package). The output is
 * sorted and has no timestamp, so rerunning the survey on the same inputs changes nothing.
 */
final class Backlog {

    private static final int SYMBOLS_PER_ITEM = 12;
    private static final int PACKAGES_PER_ITEM = 4;

    private final String version;
    private final String teavmVersion;
    private final int jdk;
    private final String entryPoint;
    private final Set<String> reachableClasses;
    private final Origins origins;
    private final List<Main.LibraryDecision> libraries;
    private final List<Main.Classified> findings;

    Backlog(
            String version,
            String teavmVersion,
            int jdk,
            String entryPoint,
            Set<String> reachableClasses,
            Origins origins,
            List<Main.LibraryDecision> libraries,
            List<Main.Classified> findings) {
        this.version = version;
        this.teavmVersion = teavmVersion;
        this.jdk = jdk;
        this.entryPoint = entryPoint;
        this.reachableClasses = reachableClasses;
        this.origins = origins;
        this.libraries = libraries;
        this.findings = findings;
    }

    /** Counts for one category or work item. A call site is one distinct (symbol, caller, line). */
    private record Tally(int items, long symbols, long sites) {}

    private static Tally tally(List<Main.Classified> group) {
        long symbols = group.stream().map(c -> c.finding().symbol()).distinct().count();
        long items = group.stream()
                .map(c -> c.rule() == null ? null : c.rule().reason())
                .distinct()
                .count();
        return new Tally((int) items, symbols, group.size());
    }

    String render() {
        Map<SurveyRules.Category, List<Main.Classified>> byCategory = new LinkedHashMap<>();
        for (SurveyRules.Category category : SurveyRules.Category.values()) {
            byCategory.put(category, new ArrayList<>());
        }
        List<Main.Classified> unclassified = new ArrayList<>();
        for (Main.Classified c : findings) {
            if (c.rule() == null) {
                unclassified.add(c);
            } else {
                byCategory
                        .computeIfAbsent(c.rule().category(), k -> new ArrayList<>())
                        .add(c);
            }
        }

        StringBuilder md = new StringBuilder();
        md.append("# Port backlog: Minecraft ").append(version).append(" under TeaVM\n\n");
        md.append("Generated by `./incari survey`. Don't edit it by hand: change `")
                .append(Main.RULES_FILE)
                .append("` and rerun.\n\n");

        Tally total = tally(findings);
        md.append("TeaVM ")
                .append(teavmVersion)
                .append(" (WebAssembly GC) reaches ")
                .append(String.format(Locale.ROOT, "%,d", reachableClasses.size()))
                .append(" classes when every client class is a root (not just what `")
                .append(entryPoint)
                .append("` reaches). ")
                .append(String.format(Locale.ROOT, "%,d", total.sites()))
                .append(" call sites use ")
                .append(String.format(Locale.ROOT, "%,d", total.symbols()))
                .append(" APIs the browser build can't provide as-is, grouped below into ")
                .append(byCategory.values().stream()
                        .mapToInt(g -> tally(g).items())
                        .sum())
                .append(" work items.\n\n");

        md.append("## Summary\n\n");
        md.append("| Category | Meaning | Work items | APIs | Call sites |\n");
        md.append("| --- | --- | ---: | ---: | ---: |\n");
        for (Map.Entry<SurveyRules.Category, List<Main.Classified>> entry : byCategory.entrySet()) {
            Tally t = tally(entry.getValue());
            md.append("| ")
                    .append(entry.getKey().title())
                    .append(" | ")
                    .append(entry.getKey().meaning())
                    .append(" | ")
                    .append(t.items())
                    .append(" | ")
                    .append(t.symbols())
                    .append(" | ")
                    .append(t.sites())
                    .append(" |\n");
        }
        if (!unclassified.isEmpty()) {
            Tally t = tally(unclassified);
            md.append("| Unclassified | No rule matched yet. | - | ")
                    .append(t.symbols())
                    .append(" | ")
                    .append(t.sites())
                    .append(" |\n");
        }
        md.append("| **Total** | | ")
                .append(byCategory.values().stream()
                        .mapToInt(g -> tally(g).items())
                        .sum())
                .append(" | ")
                .append(total.symbols())
                .append(" | ")
                .append(total.sites())
                .append(" |\n\n");

        md.append("By kind of finding:\n\n");
        md.append("| Kind | Call sites | What it means |\n| --- | ---: | --- |\n");
        Map<Finding.Kind, Long> byKind = findings.stream()
                .collect(Collectors.groupingBy(c -> c.finding().kind(), TreeMap::new, Collectors.counting()));
        for (Map.Entry<Finding.Kind, Long> entry : byKind.entrySet()) {
            md.append("| ")
                    .append(entry.getKey().label())
                    .append(" | ")
                    .append(entry.getValue())
                    .append(" | ")
                    .append(kindMeaning(entry.getKey()))
                    .append(" |\n");
        }
        md.append('\n');

        for (Map.Entry<SurveyRules.Category, List<Main.Classified>> entry : byCategory.entrySet()) {
            renderCategory(md, entry.getKey(), entry.getValue());
        }
        if (!unclassified.isEmpty()) {
            md.append("## Unclassified\n\n");
            md.append("No rule in `")
                    .append(Main.RULES_FILE)
                    .append("` matches these yet. Add rules until this section disappears.\n\n");
            renderSymbols(md, unclassified, Integer.MAX_VALUE);
        }

        renderInputs(md);
        md.append("## Reading this backlog\n\n");
        md.append("- **It's the first layer.** TeaVM stops following calls at anything it can't resolve, so stubbing"
                + " these items uncovers more. Rerun the survey after each round of porting work.\n");
        md.append("- **Call sites** are distinct (API, calling class, line) triples. Findings TeaVM reported inside JDK"
                + " or class-library code are charged to the nearest game or library method that calls into it.\n");
        md.append("- **JDK classes TeaVM lacks.** Left alone, TeaVM would copy them from the JDK running the compile,"
                + " dragging in JDK internals that can't work in a browser. The survey hides the host JDK, so each is"
                + " listed where the game uses it.\n");
        md.append("- **Whole client, not one path.** Every class in the client jar is an analysis root, except the"
                        + " `no-root` packages in `")
                .append(Main.RULES_FILE)
                .append(
                        "` (data generators, dedicated server)."
                                + " Code only the integrated server runs is included; singleplayer is deferred, but its code ships.\n");
        md.append("- **Stubs let the analysis continue.** TeaVM stops at anything missing, so the survey compiles in"
                + " rounds, stubbing what each round reports, until nothing new appears. Stubbed items are still"
                + " findings.\n");
        md.append("- **Full detail** (every call site with its method and line) is in `work/survey/")
                .append(version)
                .append("/findings.json` after a local run. It stays out of git because it names"
                        + " Mojang methods.\n");
        return md.toString();
    }

    /** The reason of the rule that classified {@code c}; category groups hold only classified findings. */
    private static String ruleReason(Main.Classified c) {
        SurveyRules.TriageRule rule = c.rule();
        if (rule == null) {
            throw new IllegalStateException(
                    "Unclassified finding in a category group: " + c.finding().symbol());
        }
        return rule.reason();
    }

    private void renderCategory(StringBuilder md, SurveyRules.Category category, List<Main.Classified> group) {
        md.append("## ").append(category.title()).append("\n\n");
        if (group.isEmpty()) {
            md.append("Nothing in this category.\n\n");
            return;
        }
        Tally t = tally(group);
        md.append(category.meaning())
                .append(' ')
                .append(t.items())
                .append(" work items, ")
                .append(t.symbols())
                .append(" APIs, ")
                .append(t.sites())
                .append(" call sites.\n\n");

        // Several rule lines may share a reason: together they are one work item.
        Map<String, List<Main.Classified>> byItem = group.stream()
                .collect(Collectors.groupingBy(Backlog::ruleReason, LinkedHashMap::new, Collectors.toList()));
        List<Map.Entry<String, List<Main.Classified>>> items = new ArrayList<>(byItem.entrySet());
        items.sort(Comparator.<Map.Entry<String, List<Main.Classified>>>comparingInt(
                        e -> -e.getValue().size())
                .thenComparing(Map.Entry::getKey));

        md.append("| Work item | APIs | Call sites | Where the calls are |\n| --- | ---: | ---: | --- |\n");
        for (Map.Entry<String, List<Main.Classified>> item : items) {
            Tally it = tally(item.getValue());
            md.append("| ")
                    .append(escape(item.getKey()))
                    .append(" | ")
                    .append(it.symbols())
                    .append(" | ")
                    .append(it.sites())
                    .append(" | ")
                    .append(callerSummary(item.getValue()))
                    .append(" |\n");
        }
        md.append('\n');

        for (Map.Entry<String, List<Main.Classified>> item : items) {
            md.append("### ").append(escape(item.getKey())).append("\n\n");
            renderSymbols(md, item.getValue(), SYMBOLS_PER_ITEM);
        }
    }

    private void renderSymbols(StringBuilder md, List<Main.Classified> group, int limit) {
        Map<String, List<Main.Classified>> bySymbol = group.stream()
                .collect(Collectors.groupingBy(c -> c.finding().symbol(), TreeMap::new, Collectors.toList()));
        List<Map.Entry<String, List<Main.Classified>>> symbols = new ArrayList<>(bySymbol.entrySet());
        symbols.sort(Comparator.<Map.Entry<String, List<Main.Classified>>>comparingInt(
                        e -> -e.getValue().size())
                .thenComparing(Map.Entry::getKey));

        md.append("| API | Kind | Call sites |\n| --- | --- | ---: |\n");
        int shown = 0;
        for (Map.Entry<String, List<Main.Classified>> symbol : symbols) {
            if (shown++ == limit) {
                int restSites = symbols.subList(limit, symbols.size()).stream()
                        .mapToInt(e -> e.getValue().size())
                        .sum();
                md.append("| ...and ")
                        .append(symbols.size() - limit)
                        .append(" more | | ")
                        .append(restSites)
                        .append(" |\n");
                break;
            }
            String kinds = symbol.getValue().stream()
                    .map(c -> c.finding().kind().label())
                    .distinct()
                    .sorted()
                    .collect(Collectors.joining(", "));
            md.append("| `")
                    .append(symbol.getKey())
                    .append("` | ")
                    .append(kinds)
                    .append(" | ")
                    .append(symbol.getValue().size())
                    .append(" |\n");
        }
        md.append('\n');
    }

    /** "net.minecraft.client.renderer (40), guava (3)": where the calls come from, by package. */
    private String callerSummary(List<Main.Classified> group) {
        Map<String, Long> counts =
                group.stream().collect(Collectors.groupingBy(c -> callerArea(c), HashMap::new, Collectors.counting()));
        List<Map.Entry<String, Long>> sorted = new ArrayList<>(counts.entrySet());
        sorted.sort(Map.Entry.<String, Long>comparingByValue().reversed().thenComparing(Map.Entry::getKey));
        String shown = sorted.stream()
                .limit(PACKAGES_PER_ITEM)
                .map(e -> "`" + e.getKey() + "` (" + e.getValue() + ")")
                .collect(Collectors.joining(", "));
        return sorted.size() > PACKAGES_PER_ITEM
                ? shown + ", +" + (sorted.size() - PACKAGES_PER_ITEM) + " more"
                : shown;
    }

    /** A Minecraft caller's package, or a library's name. Never a Mojang class or member name. */
    private String callerArea(Main.Classified c) {
        String caller = c.finding().caller();
        if (caller == null) {
            return "unknown";
        }
        String origin = origins.of(caller);
        if (!Origins.MINECRAFT.equals(origin)) {
            return origin;
        }
        int dot = caller.lastIndexOf('.');
        return dot > 0 ? caller.substring(0, dot) : caller;
    }

    private void renderInputs(StringBuilder md) {
        md.append("## Inputs\n\n");
        md.append("- Minecraft ")
                .append(version)
                .append(", entry point `")
                .append(entryPoint)
                .append("` plus every client class except the `no-root` packages\n");
        md.append("- TeaVM ")
                .append(teavmVersion)
                .append(", WebAssembly GC target, run on JDK ")
                .append(jdk)
                .append('\n');
        Map<String, Long> reachable = reachableClasses.stream()
                .collect(Collectors.groupingBy(this::originGroup, TreeMap::new, Collectors.counting()));
        md.append("- Reachable classes by origin: ")
                .append(reachable.entrySet().stream()
                        .sorted(Map.Entry.<String, Long>comparingByValue()
                                .reversed()
                                .thenComparing(Map.Entry::getKey))
                        .map(e -> e.getKey() + " " + String.format(Locale.ROOT, "%,d", e.getValue()))
                        .collect(Collectors.joining(", ")))
                .append("\n\n");

        md.append("Libraries, as decided in `")
                .append(Main.RULES_FILE)
                .append("`. Only `keep` libraries are compiled;"
                        + " calls into the others show up above as missing classes at their call sites.\n\n");
        md.append("| Library | Decision | Why |\n| --- | --- | --- |\n");
        for (Main.LibraryDecision lib : libraries.stream()
                .sorted(Comparator.comparing((Main.LibraryDecision l) -> l.action())
                        .thenComparing(Main.LibraryDecision::coordinates))
                .toList()) {
            md.append("| `")
                    .append(lib.coordinates())
                    .append("` | ")
                    .append(lib.action().name().toLowerCase(Locale.ROOT))
                    .append(" | ")
                    .append(escape(lib.reason()))
                    .append(" |\n");
        }
        md.append('\n');
    }

    private String originGroup(String className) {
        if (className.startsWith("incari.survey.")) {
            return "survey roots";
        }
        if (!origins.appClass(className).equals(className)) {
            return "generated lambda classes";
        }
        String origin = origins.of(className);
        return switch (origin) {
            case Origins.MINECRAFT -> "Minecraft";
            case Origins.TEAVM -> "TeaVM class library";
            case Origins.HOST_JDK -> "stubbed JDK classes";
            case Origins.ABSENT -> "stubbed library classes";
            default -> "libraries";
        };
    }

    private static String kindMeaning(Finding.Kind kind) {
        return switch (kind) {
            case MISSING_CLASS ->
                "TeaVM can't find the class: not in its class library, or in a library left off the classpath";
            case MISSING_METHOD -> "The class exists in TeaVM's class library but lacks this method";
            case MISSING_FIELD -> "The class exists but lacks this field";
            case UNSUPPORTED_CLASS, UNSUPPORTED_METHOD -> "TeaVM knows it but can't support it on WebAssembly GC";
            case MISSING_SUPERTYPE -> "A class extends or implements something that isn't on the classpath";
            case MISSING_BOOTSTRAP -> "An invokedynamic TeaVM can't compile";
            case NATIVE -> "A JNI method; nothing to call in a browser";
            case HOST_JDK -> "A JDK class that TeaVM's class library doesn't have; the game or a library uses it here";
            case REFLECTION -> "Reflective lookup that TeaVM's closed-world compile can't see";
            case OTHER -> "Any other compiler error";
        };
    }

    private static String escape(String text) {
        return text.replace("|", "\\|");
    }

    void printSummary() {
        Map<String, Long> counts = findings.stream()
                .collect(Collectors.groupingBy(
                        c -> c.rule() == null
                                ? "unclassified"
                                : c.rule().category().title().toLowerCase(Locale.ROOT),
                        TreeMap::new,
                        Collectors.counting()));
        Function<String, Long> get = key -> counts.getOrDefault(key, 0L);
        Log.info("Call sites: stub " + get.apply("stub") + ", shim " + get.apply("shim") + ", rewrite "
                + get.apply("rewrite") + ", delete " + get.apply("delete") + ", unclassified "
                + get.apply("unclassified"));
    }
}
